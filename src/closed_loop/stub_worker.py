"""Brain-side stub for the thin FlyBody slice (SS6).

This worker is NOT a brain. It emits a scripted, SYNTHETIC pooled
MN9-rate profile -- a ramp 0 -> 100 -> 0 Hz over 60 chunks (linear up
over chunks 0-14, hold at 100 Hz over chunks 15-34, linear down over
chunks 35-49, and 0 Hz for chunks 50-59, so the SS4.2 estimator and
the body have room to decay inside the window -- see THIN-SLICE.md
for why the tail is shaped this way) -- realised as seeded Poisson
spike counts
split evenly over the two MN9 sides, and it logs the SS4.5 taste-event
state the driver sends back with each chunk request. The profile is
generated in full, and the Poisson train drawn, at "start" -- before
the episode clock -- which is the SS2.2 harness rule's substance for
this deliverable (everything declared and prepared up front; the stub
has no code objects to compile, so Brian2's first-use compile cost
does not arise).

The stub log (JSON lines, path from the start message) is the
brain-side log SS6 criterion (iv) judges: the taste event must appear
in it exactly one chunk after the first contact chunk and clear
exactly one chunk after the contact clears. The driver sends chunk
k's request carrying the event state at the end of body chunk k-1,
so the log's chunk-k line is where that state must show up.

Protocol: protocol.py (the Part 2b bridge contract's form). stdout
carries protocol lines only; diagnostics go to stderr.

Runs under the body env's Python (no Brian2 involved on either side
of this bridge instance); the driver records the interpreter in the
run artefact.
"""

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import protocol  # noqa: E402

PEAK_RATE_HZ = 100.0
UP_CHUNKS = 15          # chunks 0..14: linear ramp up
HOLD_END_CHUNK = 35     # chunks 15..34: hold at peak
DOWN_END_CHUNK = 50     # chunks 35..49: linear ramp down; 50..59: zero


def scripted_rate(chunk, n_chunks):
    """The synthetic ramp profile, in Hz, for one chunk."""
    if chunk < UP_CHUNKS:
        return PEAK_RATE_HZ * (chunk + 1) / UP_CHUNKS
    if chunk < HOLD_END_CHUNK:
        return PEAK_RATE_HZ
    if chunk < DOWN_END_CHUNK:
        return PEAK_RATE_HZ * (DOWN_END_CHUNK - 1 - chunk) / (
            DOWN_END_CHUNK - HOLD_END_CHUNK)
    return 0.0


def main():
    log_file = None
    try:
        first = protocol.loads_line(sys.stdin.readline())
        if first.get("type") != "start":
            raise ValueError(f"expected a 'start' message, got {first!r}")
        seed = first["seed"]
        n_chunks = first["n_chunks"]
        log_path = Path(first["log_path"])
        log_path.parent.mkdir(parents=True, exist_ok=True)
        log_file = open(log_path, "w")

        # SS2.2 substance: the whole profile and its Poisson
        # realisation are prepared now, before the episode clock.
        rng = np.random.default_rng(seed)
        rates = [scripted_rate(k, n_chunks) for k in range(n_chunks)]
        counts = []
        for rate in rates:
            left = int(rng.poisson(rate / 2 * 0.1))
            right = int(rng.poisson(rate / 2 * 0.1))
            counts.append((left, right))

        profile_record = {
            "kind": "scripted_pooled_mn9_rate_profile",
            "synthetic": True,
            "shape": ("linear 0->100 Hz over chunks 0-14, hold "
                      "100 Hz over chunks 15-34, linear 100->0 Hz "
                      "over chunks 35-49, 0 Hz over chunks 50-59"),
            "peak_rate_hz": PEAK_RATE_HZ,
            "n_chunks": n_chunks,
            "poisson_seed": seed,
            "note": ("SYNTHETIC -- generated by the stub, not brain "
                     "output; it impersonates no neural data"),
        }
        log_file.write(json.dumps({"type": "profile",
                                   **profile_record}) + "\n")
        log_file.flush()
        sys.stdout.write(protocol.dumps_line(
            {"type": "ready", "n_chunks": n_chunks,
             "profile": profile_record}))
        sys.stdout.flush()

        for line in sys.stdin:
            msg = protocol.loads_line(line)
            if msg.get("type") == "end":
                log_file.write(json.dumps({"type": "end"}) + "\n")
                log_file.flush()
                sys.stdout.write(protocol.dumps_line({"type": "bye"}))
                sys.stdout.flush()
                return 0
            if msg.get("type") != "chunk":
                raise ValueError(f"expected a 'chunk' message, got {msg!r}")
            k = msg["chunk"]
            if not 0 <= k < n_chunks:
                raise ValueError(f"chunk {k} outside the declared "
                                 f"profile length {n_chunks}")
            taste = bool(msg["taste_event"])
            left, right = counts[k]
            log_file.write(json.dumps({
                "type": "chunk", "chunk": k,
                "taste_event": taste,
                "scripted_rate_hz": rates[k],
                "counts": {"mn9_left": left, "mn9_right": right},
                "synthetic": True}) + "\n")
            log_file.flush()
            sys.stdout.write(protocol.dumps_line({
                "type": "rate", "chunk": k,
                "scripted_rate_hz": rates[k],
                "counts": {"mn9_left": left, "mn9_right": right},
                "taste_event_received": taste}))
            sys.stdout.flush()
        raise RuntimeError("driver closed the bridge without 'end'")
    except Exception as exc:  # report through the protocol, then fail
        try:
            sys.stdout.write(protocol.dumps_line(
                {"type": "error", "message": f"{type(exc).__name__}: {exc}"}))
            sys.stdout.flush()
        finally:
            print(f"stub_worker error: {exc}", file=sys.stderr)
            if log_file is not None:
                log_file.close()
            return 1


if __name__ == "__main__":
    sys.exit(main())
